import { readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { LAND_RINGS, landRings } from "./land";
import { latLonToVec } from "./motion";
import { MAP_H, MAP_W, type MapContext, type MapPalette, STITCH_DASH, drawMap, landPrepared, mapX, mapY, onLand, prepareRing } from "./texture";

const PALETTE: MapPalette = { sea: "sea", land: "land", coast: "coast", thread: "thread" };

type Call = { op: string; args: unknown[]; fillStyle: unknown; strokeStyle: unknown };

/** A 2D context that records every call, with the styles set when it was made. */
function recorder(): MapContext & { calls: Call[] } {
  const calls: Call[] = [];
  const ctx = {
    calls,
    fillStyle: "" as unknown,
    strokeStyle: "" as unknown,
    lineWidth: 1,
    globalAlpha: 1,
    lineJoin: "miter" as CanvasLineJoin,
    lineCap: "butt" as CanvasLineCap,
  } as MapContext & { calls: Call[] };
  for (const op of ["setLineDash", "beginPath", "moveTo", "lineTo", "closePath", "fill", "stroke", "fillRect", "save", "restore"] as const) {
    (ctx as unknown as Record<string, unknown>)[op] = (...args: unknown[]) => {
      calls.push({ op, args, fillStyle: ctx.fillStyle, strokeStyle: ctx.strokeStyle });
    };
  }
  return ctx;
}

/** The calls between each beginPath and the fill or stroke that ends it. */
function paths(calls: Call[]) {
  const out: { end: Call; body: Call[] }[] = [];
  let body: Call[] | null = null;
  for (const c of calls) {
    if (c.op === "beginPath") body = [];
    else if ((c.op === "fill" || c.op === "stroke") && body !== null) {
      out.push({ end: c, body });
      body = null;
    } else if (body !== null) body.push(c);
  }
  return out;
}

describe("the land file", () => {
  it("is generated, names its source, and stays under 60 KB", () => {
    const file = join(__dirname, "land.ts");
    expect(statSync(file).size).toBeLessThan(60 * 1024);
    const head = readFileSync(file, "utf8").slice(0, 400);
    expect(head).toContain("GENERATED by scripts/radio-land.mjs");
    expect(head).toContain("Natural Earth");
  });

  it("decodes to rings of points inside the map", () => {
    expect(LAND_RINGS.length).toBeGreaterThan(50);
    for (const r of landRings()) {
      expect(r.length % 2).toBe(0);
      expect(r.length).toBeGreaterThanOrEqual(6);
      for (let i = 0; i < r.length; i += 2) {
        expect(Math.abs(r[i]!)).toBeLessThanOrEqual(180);
        expect(Math.abs(r[i + 1]!)).toBeLessThanOrEqual(90);
      }
    }
  });
});

describe("land and sea", () => {
  const cities: [string, number, number][] = [
    ["Paris", 48.86, 2.35],
    ["Sydney", -33.87, 151.21],
    ["Sao Paulo", -23.55, -46.63],
    ["Nairobi", -1.29, 36.82],
    ["Denver", 39.74, -104.99],
    ["Moscow", 55.76, 37.62],
    ["Vostok", -78.46, 106.84],
    ["the South Pole", -89.5, 0],
    ["Anadyr", 64.73, 177.5],
  ];
  it.each(cities)("puts %s on land", (_name, lat, lon) => {
    expect(onLand(lat, lon)).toBe(true);
  });

  const seas: [string, number, number][] = [
    ["the mid-Pacific", 0, -150],
    ["the mid-Atlantic", 30, -40],
    ["the Indian Ocean", -20, 80],
    ["the Southern Ocean", -60, 0],
    ["the Bering Sea", 58, -175],
  ];
  it.each(seas)("leaves %s as sea", (_name, lat, lon) => {
    expect(onLand(lat, lon)).toBe(false);
  });

  it("puts a city's light on its land in the map, by the same convention as the sphere", () => {
    // The vector a station light sits at, read back to longitude and latitude, lands on the same map pixel.
    for (const [, lat, lon] of cities) {
      const [x, y, z] = latLonToVec(lat, lon);
      const backLat = (Math.asin(y) * 180) / Math.PI;
      const backLon = (Math.atan2(x, z) * 180) / Math.PI;
      expect(mapX(backLon, MAP_W)).toBeCloseTo(mapX(lon, MAP_W), 6);
      expect(mapY(backLat, MAP_H)).toBeCloseTo(mapY(lat, MAP_H), 6);
      expect(onLand(backLat, backLon)).toBe(true);
    }
  });
});

describe("prepareRing", () => {
  it("unwraps a ring across the antimeridian and draws it again shifted", () => {
    const r = prepareRing([178, 10, -178, 10, -178, 12, 178, 12]);
    expect(Array.from(r.pts)).toEqual([178, 10, 182, 10, 182, 12, 178, 12]);
    expect(r.shifts).toEqual([0, -360]);
    expect(r.polar).toBe(0);
    expect(r.coast.every(Boolean)).toBe(true);
  });

  it("closes a ring round the south pole along the map's bottom edge, and does not call that edge coast", () => {
    const raw: number[] = [];
    for (let lon = -180; lon < 180; lon += 20) raw.push(lon, -70 - (lon % 40 === 0 ? 2 : 0));
    const r = prepareRing(raw);
    expect(r.polar).toBe(-1);
    const n = r.pts.length / 2;
    expect(r.coast).toHaveLength(n);
    let poleEdges = 0;
    for (let i = 0; i < n; i++) {
      const j = (i + 1) % n;
      if (r.pts[2 * i + 1] === -90 || r.pts[2 * j + 1] === -90) {
        expect(r.coast[i]).toBe(false);
        poleEdges++;
      }
    }
    expect(poleEdges).toBeGreaterThan(2);
    expect(onLand(-85, 0, [r])).toBe(true);
    expect(onLand(-60, 0, [r])).toBe(false);
  });
});

describe("drawMap", () => {
  const ctx = recorder();
  drawMap(ctx, MAP_W, MAP_H, PALETTE);
  const all = paths(ctx.calls);

  it("fills the sea first, over the whole map", () => {
    const first = ctx.calls.find((c) => c.op === "fillRect" || c.op === "fill");
    expect(first?.op).toBe("fillRect");
    expect(first?.args).toEqual([0, 0, MAP_W, MAP_H]);
    expect(first?.fillStyle).toBe("sea");
  });

  it("fills land even-odd, with every ring closed", () => {
    const fills = all.filter((p) => p.end.op === "fill");
    expect(fills).toHaveLength(1);
    expect(fills[0]!.end.args).toEqual(["evenodd"]);
    expect(fills[0]!.end.fillStyle).toBe("land");
    const body = fills[0]!.body;
    const moves = body.filter((c) => c.op === "moveTo").length;
    expect(moves).toBe(landPrepared().reduce((n, r) => n + r.shifts.length, 0));
    // Each subpath ends with closePath before the next moveTo.
    body.forEach((c, i) => {
      if (c.op === "moveTo" && i > 0) expect(body[i - 1]!.op).toBe("closePath");
    });
    expect(body[body.length - 1]!.op).toBe("closePath");
  });

  it("strokes the coast in the coast colour, and the graticule dashed in the thread colour", () => {
    const strokes = all.filter((p) => p.end.op === "stroke");
    expect(strokes.map((s) => s.end.strokeStyle)).toEqual(["coast", "coast", "thread"]);
    const dashes = ctx.calls.filter((c) => c.op === "setLineDash").map((c) => c.args[0]);
    expect(dashes).toContainEqual([...STITCH_DASH]);
    // Meridians every 30 degrees, both edges included, and the five parallels between the poles.
    const grid = strokes[2]!.body.filter((c) => c.op === "moveTo");
    expect(grid).toHaveLength(13 + 5);
  });

  it("never draws a segment across more than half the map", () => {
    for (const p of all) {
      let at: [number, number] | null = null;
      let start: [number, number] | null = null;
      for (const c of p.body) {
        const pt = c.args as [number, number];
        if (c.op === "moveTo") at = start = pt;
        else if (c.op === "lineTo" && at !== null) {
          expect(Math.abs(pt[0] - at[0])).toBeLessThanOrEqual(MAP_W / 2);
          at = pt;
        } else if (c.op === "closePath" && at !== null && start !== null) {
          expect(Math.abs(start[0] - at[0])).toBeLessThanOrEqual(MAP_W / 2);
        }
      }
    }
  });

  it("restores the context it was given", () => {
    expect(ctx.calls[0]!.op).toBe("save");
    expect(ctx.calls[ctx.calls.length - 1]!.op).toBe("restore");
  });
});
