#!/usr/bin/env node
// Writes the radio globe's land outlines (brief 047 part C): apps/web/src/components/radio/globe/land.ts.
// Source: Natural Earth 1:110m land (public domain), as TopoJSON in the world-atlas@2.0.2 package. The TopoJSON is
// decoded here by hand, with no dependency: each arc is delta-decoded and placed with the file's transform, arcs are
// stitched into rings (a negative index ~i means arc i reversed), and each ring is written as one string of
// 4-character points (longitude, then latitude, in tenths of a degree, base 64). Run by hand, with Node 24:
//   node scripts/radio-land.mjs            fetch, decode and write
//   node scripts/radio-land.mjs --dry      fetch and decode, print the counts, write nothing
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const LAND_URL = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json";
export const OUT_FILE = "apps/web/src/components/radio/globe/land.ts";
/** 64 characters that are safe inside a double-quoted string and never start a comment. */
export const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_$";
const MAX_BYTES = 60 * 1024;

/** Delta-decodes every arc and applies the transform: an array of [lon, lat] arrays. */
export function decodeArcs(topo) {
  const t = topo.transform;
  return topo.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return t ? [x * t.scale[0] + t.translate[0], y * t.scale[1] + t.translate[1]] : [x, y];
    });
  });
}

/** One ring from its arc indexes. Each arc after the first starts where the last ended, so its first point is dropped. */
export function stitchRing(indexes, arcs) {
  const ring = [];
  for (const i of indexes) {
    const pts = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
    for (let k = ring.length === 0 ? 0 : 1; k < pts.length; k++) ring.push(pts[k]);
  }
  return ring;
}

/** Every ring of every polygon in the object, outer rings and holes alike (the globe fills them even-odd). */
export function objectRings(topo, name) {
  const arcs = decodeArcs(topo);
  const rings = [];
  const visit = (g) => {
    if (g.type === "GeometryCollection") g.geometries.forEach(visit);
    else if (g.type === "Polygon") for (const r of g.arcs) rings.push(stitchRing(r, arcs));
    else if (g.type === "MultiPolygon") for (const p of g.arcs) for (const r of p) rings.push(stitchRing(r, arcs));
  };
  visit(topo.objects[name]);
  return rings;
}

/** Tenths of a degree from 0, so every number is a small non-negative integer. */
export function quantise(ring) {
  const out = [];
  for (const [lon, lat] of ring) {
    const q = [Math.round((Math.max(-180, Math.min(180, lon)) + 180) * 10), Math.round((Math.max(-90, Math.min(90, lat)) + 90) * 10)];
    const last = out[out.length - 1];
    if (last === undefined || last[0] !== q[0] || last[1] !== q[1]) out.push(q);
  }
  // A closed ring repeats its first point last; the drawing closes it instead.
  if (out.length > 1 && out[0][0] === out[out.length - 1][0] && out[0][1] === out[out.length - 1][1]) out.pop();
  return out;
}

const two = (n) => ALPHABET[n >> 6] + ALPHABET[n & 63];
export const encodeRing = (q) => q.map(([x, y]) => two(x) + two(y)).join("");

export function landSource(rings) {
  const lines = [
    "// GENERATED by scripts/radio-land.mjs. Do not edit by hand; run the script again.",
    "// Source: Natural Earth 1:110m land (public domain, naturalearthdata.com), as TopoJSON in world-atlas@2.0.2",
    `// (${LAND_URL}). Every ring of every polygon, holes included: fill them even-odd.`,
    "// Each ring is one string of 4-character points: longitude then latitude, each in tenths of a degree from -180",
    "// and -90, as two base-64 digits of LAND_ALPHABET. A ring is closed: its last point joins its first.",
    "",
    `export const LAND_ALPHABET = "${ALPHABET}";`,
    "",
    "export const LAND_RINGS: readonly string[] = [",
    ...rings.map((r) => `  "${r}",`),
    "];",
    "",
    "/** One ring as [lon0, lat0, lon1, lat1, ...] in degrees. */",
    "export function decodeLandRing(ring: string): Float32Array {",
    "  const out = new Float32Array(ring.length / 2);",
    "  const d = (i: number) => LAND_ALPHABET.indexOf(ring[i]!) * 64 + LAND_ALPHABET.indexOf(ring[i + 1]!);",
    "  for (let p = 0; p < ring.length / 4; p++) {",
    "    out[2 * p] = d(4 * p) / 10 - 180;",
    "    out[2 * p + 1] = d(4 * p + 2) / 10 - 90;",
    "  }",
    "  return out;",
    "}",
    "",
    "let decoded: readonly Float32Array[] | null = null;",
    "",
    "/** Every land ring, decoded once. */",
    "export function landRings(): readonly Float32Array[] {",
    "  decoded ??= LAND_RINGS.map(decodeLandRing);",
    "  return decoded;",
    "}",
    "",
  ];
  return lines.join("\n");
}

async function main() {
  const dry = process.argv.includes("--dry");
  const res = await fetch(LAND_URL, { headers: { "User-Agent": "franki-radio-land/1" }, signal: AbortSignal.timeout(20000) });
  if (!res.ok) throw new Error(`${LAND_URL} answered ${res.status}`);
  const topo = await res.json();
  if (topo.type !== "Topology" || !topo.objects.land) throw new Error("not the world-atlas land topology");
  const rings = objectRings(topo, "land").map(quantise).filter((q) => q.length >= 3);
  const source = landSource(rings.map(encodeRing));
  const bytes = Buffer.byteLength(source, "utf8");
  const points = rings.reduce((n, r) => n + r.length, 0);
  console.log(`${rings.length} rings, ${points} points, ${bytes} bytes`);
  if (bytes > MAX_BYTES) throw new Error(`land.ts would be ${bytes} bytes, over ${MAX_BYTES}`);
  if (dry) return;
  const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
  writeFileSync(join(root, OUT_FILE), source);
  console.log(`wrote ${OUT_FILE}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
}
