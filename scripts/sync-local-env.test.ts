import { readFileSync } from "node:fs";
import fc from "fast-check";
import { describe, expect, it } from "vitest";
import { APPHOSTING_PATH, formatEnvFile, parsePlainEnv, summary, withQuotaProject } from "./sync-local-env.mjs";

const SAMPLE = `
runConfig:
  cpu: 1
env:
  - variable: FRANKI_VOICE_MODEL
    value: voice-model-x
  - variable: FRANKI_FIREBASE_PROJECT_ID
    value: demo-project
    availability:
      - BUILD
      - RUNTIME
  - variable: OPENAI_API_KEY
    secret: OPENAI_API_KEY
    availability:
      - RUNTIME
  - variable: SOMETHING
    unknownKey: ignored
  - variable: NEXT_PUBLIC_PORT
    value: 3000
`;

describe("parsePlainEnv", () => {
  it("copies plain values", () => {
    expect(parsePlainEnv(SAMPLE)).toEqual([
      { name: "FRANKI_VOICE_MODEL", value: "voice-model-x" },
      { name: "FRANKI_FIREBASE_PROJECT_ID", value: "demo-project" },
      { name: "NEXT_PUBLIC_PORT", value: "3000" },
    ]);
  });

  it("skips secret entries", () => {
    const names = parsePlainEnv(SAMPLE).map((e) => e.name);
    expect(names).not.toContain("OPENAI_API_KEY");
    expect(formatEnvFile(parsePlainEnv(SAMPLE))).not.toContain("OPENAI_API_KEY");
    // Real file: neither secret is ever copied.
    const real = parsePlainEnv(readFileSync(APPHOSTING_PATH, "utf8")).map((e) => e.name);
    expect(real).not.toContain("OPENAI_API_KEY");
    expect(real).not.toContain("SMOKE_TOKEN");
    expect(real).toContain("FRANKI_TRANSCRIBE_MODEL");
    expect(real).toContain("FRANKI_FIREBASE_PROJECT_ID");
  });

  it("ignores entries with unknown keys and no value, and a missing env list", () => {
    expect(parsePlainEnv(SAMPLE).map((e) => e.name)).not.toContain("SOMETHING");
    expect(parsePlainEnv("runConfig:\n  cpu: 1\n")).toEqual([]);
  });

  it("leaves blank deployment settings to .env.local", () => {
    expect(parsePlainEnv('env:\n  - variable: TWILIO_PHONE_NUMBER\n    value: ""')).toEqual([]);
  });

  it("prints no values", () => {
    fc.assert(
      fc.property(fc.array(fc.stringMatching(/^v-[A-Za-z0-9]{6,20}$/), { maxLength: 10 }), (values) => {
        const entries = values.map((value, i) => ({ name: `VAR_${i}`, value }));
        const line = summary(entries);
        expect(line).toBe(`synced ${values.length} plain values`);
        for (const value of values) expect(line).not.toContain(value);
      }),
    );
  });

  it("adds GOOGLE_CLOUD_QUOTA_PROJECT equal to the Firebase project ID, as a plain value", () => {
    const entries = withQuotaProject(parsePlainEnv(SAMPLE));
    expect(entries.find((e) => e.name === "GOOGLE_CLOUD_QUOTA_PROJECT")).toEqual({
      name: "GOOGLE_CLOUD_QUOTA_PROJECT",
      value: "demo-project",
    });
    expect(formatEnvFile(entries)).toContain("\nGOOGLE_CLOUD_QUOTA_PROJECT=demo-project\n");
    expect(withQuotaProject(withQuotaProject(parsePlainEnv(SAMPLE))).filter((e) => e.name === "GOOGLE_CLOUD_QUOTA_PROJECT")).toHaveLength(1);
    expect(withQuotaProject([{ name: "A", value: "x" }])).toEqual([{ name: "A", value: "x" }]);
  });

  it("does not put the quota project in apphosting.yaml", () => {
    expect(readFileSync(APPHOSTING_PATH, "utf8")).not.toContain("GOOGLE_CLOUD_QUOTA_PROJECT");
  });

  it("writes NAME=value lines under a generated-file header", () => {
    const text = formatEnvFile([
      { name: "A", value: "plain-1.2" },
      { name: "B", value: "has space" },
    ]);
    expect(text.startsWith("# Generated by scripts/sync-local-env.mjs")).toBe(true);
    expect(text).toContain("\nA=plain-1.2\n");
    expect(text).toContain('\nB="has space"\n');
  });
});
