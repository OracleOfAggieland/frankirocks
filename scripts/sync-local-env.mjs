#!/usr/bin/env node
// Local env sync (R30.10). `next dev` does not read apphosting.yaml, so `predev` copies each nonempty plain
// `value:` entry under `env:` in apps/web/apphosting.yaml into apps/web/.env.development.local.
// Secret entries are never copied (they stay in apps/web/.env.local), and no value is ever printed.
import { writeFileSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const WEB_DIR = fileURLToPath(new URL("../apps/web/", import.meta.url));
export const APPHOSTING_PATH = resolve(WEB_DIR, "apphosting.yaml");
export const OUTPUT_PATH = resolve(WEB_DIR, ".env.development.local");
const NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;
// A deployment's own address. It would shadow the localhost value in .env.local (.env.development.local wins).
const DEPLOYMENT_ONLY = new Set(["GOOGLE_OAUTH_REDIRECT_URI", "FRANKI_PHONE_REPORT_ORIGIN"]);

/**
 * Pure: returns [{ name, value }] for each `env:` entry with a `variable`, a nonempty scalar `value` and no `secret`.
 * Entries with `secret:` and deployment-only names are skipped; other keys (such as `availability`) are ignored.
 */
export function parsePlainEnv(yamlText) {
  const doc = parse(yamlText);
  const env = doc && typeof doc === "object" ? doc.env : undefined;
  if (!Array.isArray(env)) return [];
  const plain = [];
  for (const entry of env) {
    if (!entry || typeof entry !== "object") continue;
    const { variable, value, secret } = entry;
    // Empty deployment placeholders must not shadow values from .env.local in next dev.
    if (secret !== undefined || value === "") continue;
    if (DEPLOYMENT_ONLY.has(variable)) continue;
    if (typeof variable !== "string" || !NAME.test(variable)) continue;
    if (typeof value !== "string" && typeof value !== "number" && typeof value !== "boolean") continue;
    plain.push({ name: variable, value: String(value) });
  }
  return plain;
}

/**
 * Pure: local only. Local Application Default Credentials are a user login with no quota project, which makes
 * the Admin SDK's verifyIdToken(token, true) fail with auth/internal-error. Setting GOOGLE_CLOUD_QUOTA_PROJECT to
 * the Firebase project ID fixes it. Hosted code runs as a service account, so apphosting.yaml does not get it.
 */
export function withQuotaProject(entries) {
  const project = entries.find((e) => e.name === "FRANKI_FIREBASE_PROJECT_ID");
  const rest = entries.filter((e) => e.name !== "GOOGLE_CLOUD_QUOTA_PROJECT");
  return project ? [...rest, { name: "GOOGLE_CLOUD_QUOTA_PROJECT", value: project.value }] : rest;
}

function quote(value) {
  return /^[A-Za-z0-9_.:/@+-]*$/.test(value) ? value : JSON.stringify(value);
}

/** Pure: the generated file's text. */
export function formatEnvFile(entries) {
  const header = [
    "# Generated by scripts/sync-local-env.mjs from apps/web/apphosting.yaml. Do not edit; edit apphosting.yaml.",
    "# Plain values only. Secrets stay in apps/web/.env.local.",
  ];
  return [...header, ...entries.map((e) => `${e.name}=${quote(e.value)}`), ""].join("\n");
}

/** Pure: the only line the script prints. Contains a count, never a name's value. */
export function summary(entries) {
  return `synced ${entries.length} plain values`;
}

const isMain = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const entries = withQuotaProject(parsePlainEnv(readFileSync(APPHOSTING_PATH, "utf8")));
  writeFileSync(OUTPUT_PATH, formatEnvFile(entries));
  console.log(summary(entries));
}
